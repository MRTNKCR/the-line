const buildSourceUrl = (dishName) =>
  `https://www.seriouseats.com/search?q=${encodeURIComponent(dishName)}`;

const buildSummary = (seed) =>
  `${seed.name} is a globally loved ${seed.style} from ${seed.origin}, frequently highlighted in popular international rankings for ${seed.signature}.`;

const buildHistory = (seed) =>
  `Historically, ${seed.name} grew through ${seed.historyContext}, and this guided version adds explicit timing cues to make home execution smoother.`;

const deduplicateIngredients = (ingredients) => {
  const map = new Map();

  for (const ingredient of ingredients) {
    const key = `${ingredient.name.toLowerCase()}::${ingredient.unit}`;
    if (!map.has(key)) {
      map.set(key, { ...ingredient });
      continue;
    }

    const current = map.get(key);
    current.amount += ingredient.amount;
  }

  return Array.from(map.values()).sort((a, b) =>
    a.name.localeCompare(b.name, "en")
  );
};

const buildSteps = (seed) => {
  const templateFactory = METHOD_STEPS[seed.method] ?? METHOD_STEPS.stovetop;
  const templateSteps = templateFactory(seed.name);

  return templateSteps.map((step, idx) => ({
    id: `${seed.id}-step-${idx + 1}`,
    order: idx + 1,
    title: step.title,
    detail: step.detail,
    phase: step.phase,
    durationMin: step.durationMin,
    durationSec: step.durationMin * 60,
  }));
};

const toRecipe = (seed) => {
  const steps = buildSteps(seed);
  const timings = steps.reduce(
    (acc, step) => {
      acc[step.phase] += step.durationMin;
      return acc;
    },
    { prep: 0, rest: 0, cook: 0 }
  );

  return {
    id: seed.id,
    rank: seed.rank,
    name: seed.name,
    origin: seed.origin,
    basePortions: 4,
    summary: buildSummary(seed),
    history: buildHistory(seed),
    sourceUrl: buildSourceUrl(seed.name),
    sourceLabel: "Serious Eats (internet source search)",
    imageUrl: `https://source.unsplash.com/960x640/?${encodeURIComponent(seed.imageQuery)}`,
    imageThumbUrl: `https://source.unsplash.com/480x320/?${encodeURIComponent(seed.imageQuery)}`,
    timings,
    totalTimeMin: timings.prep + timings.rest + timings.cook,
    ingredients: deduplicateIngredients([
      ...seed.ingredients,
      ...UNIVERSAL_INGREDIENTS,
      ...(METHOD_EXTRA_INGREDIENTS[seed.method] ?? []),
    ]),
    steps,
  };
};

